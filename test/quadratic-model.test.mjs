import test from "node:test";
import assert from "node:assert/strict";
import { initialize, MetaModel } from "../dist/node.js";

test("quadratic MetaModel exchanges lossless objectives and normalized snapshots", async () => {
    await initialize();
    const model = new MetaModel("quadratic-model");
    const x = model.addVariable("x", { lowerBound: 0, upperBound: 5 });
    const y = model.addVariable("y", { type: "binary" });
    const token = x.token();
    const id = token.id();
    const sum = model.linearExpression([[x, 1], [y, 1]]);
    const square = sum.mul(sum);
    model.setQuadraticObjective(square);
    assert.throws(() => model.toLinearTriadModel(), { code: "Unsupported" });
    const lhs = square.add(3);
    const relation = lhs.le(7);
    model.addInequality(relation, "q-capacity");
    lhs.dispose(); relation.dispose();
    model.addLinearConstraint({ name: "linear-capacity", terms: [[x, 1]], relation: "le", rhs: 4 });
    const symbol = model.addLinearSymbol("sum", sum);
    model.setSolution(new Float64Array([1, 1]));
    const artifact = model.toQuadraticTetradModel();
    const input = JSON.parse(artifact.modelJson);
    assert.deepEqual(input.objective.quadraticCells.map(cell => [cell.colIndex1, cell.colIndex2, cell.coefficient]), [[0, 0, 1], [0, 1, 2], [1, 1, 1]]);
    assert.equal(input.quadraticConstraints[0].rhs, 4);
    assert.equal(input.quadraticConstraints.length, 1);
    const nonzero = square.add(1);
    assert.throws(() => model.setQuadraticObjective(nonzero), { code: "Unsupported" });
    assert.deepEqual(model.toQuadraticTetradModel(), artifact);
    assert.equal(token.result(), 1);
    assert.equal(symbol.evaluateSolution(), 2);
    assert.throws(() => square.le(Infinity), { code: "InvalidInput" });
    const emptyName = square.ge(0);
    assert.throws(() => model.addInequality(emptyName, " "), { code: "InvalidInput" });
    assert.deepEqual(model.toQuadraticTetradModel(), artifact);
    const other = new MetaModel("quadratic-model");
    other.addVariable("x");
    assert.throws(() => other.setQuadraticObjective(square), { code: "InvalidReference" });
    assert.throws(() => other.addInequality(emptyName, "foreign"), { code: "InvalidReference" });
    model.addVariable("later");
    assert.equal(token.id(), id);
    assert.equal(token.result(), undefined);
    assert.equal(JSON.parse(model.toQuadraticTetradModel().modelJson).variables.length, 3);
    model.setLinearObjective([[x, 1]], "maximize");
    assert.deepEqual(JSON.parse(model.toQuadraticTetradModel().modelJson).objective.quadraticCells, []);
    assert.throws(() => model.toLinearTriadModel(), { code: "Unsupported" });
    model.dispose();
    assert.throws(() => square.le(1), { code: "Disposed" });
    for (const value of [token, sum, square, symbol, nonzero, emptyName, other]) value.dispose();
});

test("quadratic objectives switch to linear without retaining stale Q terms", async () => {
    await initialize();
    const model = new MetaModel("objective-switch");
    const x = model.addVariable("x");
    const linear = x.toLinear();
    const square = linear.mul(linear);
    model.setQuadraticObjective(square);
    model.setLinearObjective(linear);
    assert.ok(model.toLinearTriadModel().fingerprint);
    model.setQuadraticObjective(linear);
    assert.deepEqual(JSON.parse(model.toQuadraticTetradModel().modelJson).objective.quadraticCells, []);
    const qrhs = square.add(2);
    const relation = square.le(qrhs);
    model.addInequality(relation, "difference");
    const row = JSON.parse(model.toQuadraticTetradModel().modelJson).quadraticConstraints[0];
    assert.deepEqual(row.quadraticCells, []);
    assert.equal(row.rhs, 2);
    for (const value of [linear, square, qrhs, relation, model]) value.dispose();
});

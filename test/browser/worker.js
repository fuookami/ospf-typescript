import { initialize, Rational, MetaModel } from '/dist/browser.js';
import { checkCp } from './cp.js';
import { checkGeometry2d } from './geometry2d.js';
await initialize();
self.postMessage({ geometry2d: checkGeometry2d() });
const value = new Rational(9007199254740993n, 3n);
const model = new MetaModel('worker-expressions');
const x = model.addVariable('x');
model.setVariableRange(x, { lowerBound: 0, upperBound: 3 });
const expression = model.linearExpression([[x, 3]], 2);
const symbol = model.addLinearSymbol('cost', expression);
const reference = symbol.toLinear();
const square = reference.mul(reference);
const quadraticSymbol = model.addQuadraticSymbol('square', square);
const quadraticReference = quadraticSymbol.toQuadratic();
const derived = model.addLinearSymbol('derived', reference);
const relation = reference.ge(5);
model.addInequality(relation, 'capacity');
const quadraticRelation = square.le(64);
model.addInequality(quadraticRelation, 'quadratic-capacity');
model.setSolution(new Float64Array([2]));
const token = x.token();
postMessage({ rational: value.toString(), linear: expression.evaluate(new Float64Array([2])), quadratic: quadraticReference.evaluate(new Float64Array([2])), quadraticSymbol: quadraticSymbol.evaluateSolution(), quadraticDependency: quadraticSymbol.dependencyIds()[0] === symbol.id(), quadraticModel: Boolean(model.toQuadraticTetradModel().fingerprint), symbol: derived.evaluateSolution(), token: token.result(), rangeUpper: token.upperBound(), dependency: derived.dependencyIds()[0] === symbol.id(), cp: checkCp() });
for (const object of [value, expression, square, reference, quadraticSymbol, quadraticReference, relation, quadraticRelation, token, symbol, derived, model]) object.dispose();

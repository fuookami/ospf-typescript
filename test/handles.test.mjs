import assert from "node:assert/strict";
import test from "node:test";
import { initialize, MetaModel } from "../dist/node.js";

test("tokens expose stable exact Rust identities and live assignments", async () => {
    await initialize();
    const model = new MetaModel("tokens");
    const x = model.addVariable("x", { lowerBound: 0, upperBound: 10 });
    const y = model.addVariable("y", { type: "integer", lowerBound: -3, upperBound: 3 });
    const token = x.token();
    const same = model.token(x);
    const id = token.id();
    assert.equal(typeof id, "bigint");
    assert.equal(same.id(), id);
    assert.equal(token.solverIndex(), 0);
    assert.equal(token.name(), "x");
    assert.equal(token.kind(), "continuous");
    assert.equal(token.lowerBound(), 0);
    assert.equal(token.upperBound(), 10);
    assert.equal(token.result(), undefined);
    const expression = token.toLinear();
    model.setLinearObjective(expression);
    model.setSolution(new Float64Array([4, -2]));
    assert.equal(same.result(), 4);
    for (const assignment of [[4], [11, 1], [4, 0.5], [NaN, 1]]) {
        assert.throws(() => model.setSolution(new Float64Array(assignment)), { code: "InvalidInput" });
        assert.equal(same.result(), 4);
    }
    model.addVariable("z", { type: "binary" });
    assert.equal(token.id(), id);
    assert.equal(token.result(), undefined);
    const tokens = model.tokens();
    assert.deepEqual(tokens.map(t => t.solverIndex()), [0, 1, 2]);
    assert.equal(tokens[1].kind(), "integer");
    assert.equal(tokens[2].kind(), "binary");
    assert.equal(tokens[2].lowerBound(), 0);
    model.setSolution(new Float64Array([1, 2, 1]));
    model.clearSolution();
    assert.equal(token.result(), undefined);
    assert.equal(tokens[0].id(), id);
    token.dispose();
    assert.throws(() => token.id(), { code: "Disposed" });
    assert.equal(same.id(), id);
    model.dispose();
    assert.throws(() => same.result(), { code: "Disposed" });
    assert.throws(() => y.token(), { code: "Disposed" });
    for (const object of [...tokens, same, expression]) object.dispose();
});

test("variable range updates retain tokens and reject invalid changes atomically", async () => {
    await initialize();
    const model = new MetaModel("range-updates");
    const x = model.addVariable("x", { lowerBound: 0, upperBound: 10 });
    const integer = model.addVariable("i", { type: "integer", lowerBound: -3, upperBound: 3 });
    const binary = model.addVariable("b", { type: "binary" });
    const token = x.token(), binaryToken = binary.token(), id = token.id();
    const trackedLinear = x.toLinear(), trackedSymbol = model.addLinearSymbol("tracked", trackedLinear);
    model.setLinearObjective([[x, 1]], "maximize");
    model.setSolution(new Float64Array([4, -2, 1]));
    assert.equal(trackedSymbol.evaluateSolution(), 4);
    const before = model.toLinearTriadModel();
    for (const [variable, range] of [
        [x, { lowerBound: NaN }], [x, { lowerBound: 4, upperBound: 3 }],
        [x, { upperBound: "2" }], [x, { lowerBound: null }],
        [integer, { lowerBound: 0.5 }], [integer, { upperBound: 9007199254740992 }],
        [binary, { lowerBound: -1 }], [binary, { upperBound: Infinity }], [x, null],
    ]) {
        assert.throws(() => model.setVariableRange(variable, range), { code: "InvalidInput" });
        assert.deepEqual(model.toLinearTriadModel(), before);
        assert.equal(token.result(), 4);
        assert.equal(trackedSymbol.evaluateSolution(), 4);
    }
    const foreign = new MetaModel("foreign"), foreignX = foreign.addVariable("x");
    assert.throws(() => foreign.setVariableRange(x, {}), { code: "InvalidReference" });
    assert.throws(() => model.setVariableRange(foreignX, {}), { code: "InvalidReference" });
    model.setVariableRange(x, { lowerBound: -2, upperBound: 3 });
    assert.equal(token.id(), id); assert.equal(token.lowerBound(), -2); assert.equal(token.upperBound(), 3);
    assert.equal(token.result(), undefined);
    assert.equal(trackedSymbol.evaluateSolution(), undefined);
    assert.notEqual(model.toLinearTriadModel().fingerprint, before.fingerprint);
    model.setVariableRange(x, {});
    assert.equal(token.lowerBound(), undefined); assert.equal(token.upperBound(), undefined);
    model.setVariableRange(binary, { lowerBound: 1 });
    assert.equal(binaryToken.lowerBound(), 1); assert.equal(binaryToken.upperBound(), 1);
    model.setVariableRange(binary, {});
    assert.equal(binaryToken.lowerBound(), 0); assert.equal(binaryToken.upperBound(), 1);
    const linear = x.toLinear(), quadratic = linear.mul(linear);
    model.setQuadraticObjective(quadratic);
    const quadraticBefore = model.toQuadraticTetradModel();
    model.setVariableRange(x, { upperBound: 2 });
    assert.notEqual(model.toQuadraticTetradModel().fingerprint, quadraticBefore.fingerprint);
    assert.deepEqual([...quadratic.quadraticTerms().coefficients], [1]);
    model.dispose();
    assert.throws(() => model.setVariableRange(x, {}), { code: "Disposed" });
    for (const value of [token, binaryToken, trackedLinear, trackedSymbol, linear, quadratic, foreign]) value.dispose();
});

test("registered Rust symbols retain dependencies through linear arithmetic", async () => {
    await initialize();
    const model = new MetaModel("symbols");
    const x = model.addVariable("x", { lowerBound: 0, upperBound: 10 });
    const input = model.linearExpression([[x, 2]], 3);
    const symbol = model.addLinearSymbol("cost", input);
    input.dispose();
    assert.equal(symbol.name(), "cost");
    assert.equal(typeof symbol.id(), "bigint");
    assert.deepEqual([...symbol.dependencyIds()], []);
    assert.equal(symbol.evaluate(new Float64Array([4])), 11);
    assert.equal(symbol.evaluateSolution(), undefined);
    const reference = symbol.toLinear();
    const doubled = reference.mul(2);
    const derived = model.addLinearSymbol("doubled", doubled);
    assert.deepEqual([...derived.dependencyIds()], [symbol.id()]);
    const combined = reference.add(doubled);
    const third = model.addLinearSymbol("combined", combined);
    assert.deepEqual([...third.dependencyIds()], [symbol.id()]);
    const fromDerived = derived.toLinear();
    const fourth = model.addLinearSymbol("nested", fromDerived);
    assert.deepEqual([...fourth.dependencyIds()], [derived.id()]);
    model.setSolution(new Float64Array([4]));
    assert.equal(symbol.evaluateSolution(), 11);
    assert.equal(derived.evaluateSolution(), 22);
    assert.equal(third.evaluateSolution(), 33);
    assert.equal(fourth.evaluateSolution(), 22);
    const unchanged = model.toLinearTriadModel();
    assert.throws(() => model.addLinearSymbol("cost", reference), { code: "DuplicateName" });
    assert.throws(() => model.addLinearSymbol(" ", reference), { code: "InvalidInput" });
    assert.deepEqual(model.toLinearTriadModel(), unchanged);
    assert.equal(symbol.evaluateSolution(), 11);
    const copy = derived.dependencyIds();
    copy[0] = 0n;
    assert.deepEqual([...derived.dependencyIds()], [symbol.id()]);
    const relation = reference.le(11);
    model.addInequality(relation, "capacity");
    assert.equal(symbol.evaluateSolution(), undefined);
    symbol.dispose();
    assert.throws(() => symbol.id(), { code: "Disposed" });
    assert.equal(derived.evaluate(new Float64Array([4])), 22);
    model.dispose();
    assert.throws(() => derived.evaluateSolution(), { code: "Disposed" });
    for (const object of [reference, doubled, derived, combined, third, fromDerived, fourth, relation]) object.dispose();
});

test("tokens and symbols cannot cross models, even when indices and names coincide", async () => {
    await initialize();
    const a = new MetaModel("same");
    const b = new MetaModel("same");
    const ax = a.addVariable("x");
    const bx = b.addVariable("x");
    const at = ax.token();
    const bt = bx.token();
    assert.notEqual(at.id(), bt.id());
    assert.throws(() => b.token(ax), { code: "InvalidReference" });
    const expression = at.toLinear();
    const symbol = a.addLinearSymbol("same", expression);
    const reference = symbol.toLinear();
    assert.throws(() => b.addLinearSymbol("same", reference), { code: "InvalidReference" });
    assert.throws(() => b.setLinearObjective(expression), { code: "InvalidReference" });
    assert.throws(() => symbol.evaluate(new Float64Array()), { code: "InvalidInput" });
    assert.throws(() => symbol.evaluate(new Float64Array([Infinity])), { code: "InvalidInput" });
    assert.equal(at.lowerBound(), undefined);
    assert.equal(at.upperBound(), undefined);
    for (const object of [at, bt, expression, symbol, reference, a, b]) object.dispose();
});

test("registered quadratic symbols retain Rust dependencies, terms and model ownership", async () => {
    await initialize();
    const model = new MetaModel("quadratic-symbols");
    const x = model.addVariable("x");
    const y = model.addVariable("y");
    const linear = model.linearExpression([[x, 2], [y, 1]], 1);
    const linearSymbol = model.addLinearSymbol("linear", linear);
    const reference = linearSymbol.toLinear();
    const xExpression = x.toLinear();
    const product = reference.mul(xExpression);
    const input = product.add(3);
    const symbol = model.addQuadraticSymbol("quadratic", input);
    input.dispose();
    assert.equal(symbol.name(), "quadratic");
    assert.equal(typeof symbol.id(), "bigint");
    assert.deepEqual([...symbol.dependencyIds()], [linearSymbol.id()]);
    assert.equal(symbol.evaluate(new Float64Array([2, 3])), 19);
    assert.equal(symbol.evaluateSolution(), undefined);
    const quadratic = symbol.toQuadratic();
    assert.equal(quadratic.evaluate(new Float64Array([2, 3])), 19);
    assert.deepEqual([...quadratic.linearCoefficients()], [1, 0]);
    const terms = quadratic.quadraticTerms();
    assert.deepEqual([...terms.rows], [0, 0]);
    assert.deepEqual([...terms.columns], [0, 1]);
    assert.deepEqual([...terms.coefficients], [2, 1]);
    const twice = quadratic.mul(2);
    const derived = model.addQuadraticSymbol("derived", twice);
    assert.deepEqual([...derived.dependencyIds()], [symbol.id()]);
    const cancelled = quadratic.sub(quadratic);
    const cancelledLinear = cancelled.tryToLinear();
    const zero = model.addLinearSymbol("zero", cancelledLinear);
    assert.deepEqual([...zero.dependencyIds()], [symbol.id()]);
    assert.equal(zero.evaluate(new Float64Array([2, 3])), 0);
    const dependencyCopy = derived.dependencyIds();
    dependencyCopy[0] = 0n;
    assert.deepEqual([...derived.dependencyIds()], [symbol.id()]);
    model.setSolution(new Float64Array([2, 3]));
    assert.equal(symbol.evaluateSolution(), 19);
    assert.equal(derived.evaluateSolution(), 38);
    const unchanged = model.toQuadraticTetradModel();
    assert.throws(() => model.addQuadraticSymbol("linear", quadratic), { code: "DuplicateName" });
    assert.throws(() => model.addLinearSymbol("quadratic", linear), { code: "DuplicateName" });
    assert.throws(() => model.addQuadraticSymbol(" ", quadratic), { code: "InvalidInput" });
    assert.deepEqual(model.toQuadraticTetradModel(), unchanged);
    assert.equal(symbol.evaluateSolution(), 19);
    assert.throws(() => symbol.evaluate(new Float64Array([2])), { code: "InvalidInput" });
    assert.throws(() => symbol.evaluate(new Float64Array([NaN, 0])), { code: "InvalidInput" });
    assert.throws(() => symbol.evaluate(new Float64Array([Number.MAX_VALUE, Number.MAX_VALUE])), { code: "InvalidInput" });
    model.setSolution(new Float64Array([Number.MAX_VALUE, Number.MAX_VALUE]));
    assert.throws(() => symbol.evaluateSolution(), { code: "InvalidInput" });
    model.setSolution(new Float64Array([2, 3]));
    const other = new MetaModel("other-quadratic");
    assert.throws(() => other.addQuadraticSymbol("foreign", quadratic), { code: "InvalidReference" });
    const objective = quadratic.sub(3);
    model.setQuadraticObjective(objective);
    assert.equal(symbol.evaluateSolution(), undefined);
    const relation = quadratic.le(19);
    model.addInequality(relation, "capacity");
    assert.ok(model.toQuadraticTetradModel().fingerprint);
    model.addVariable("later");
    assert.throws(() => symbol.evaluate(new Float64Array([2, 3])), { code: "InvalidInput" });
    assert.equal(symbol.evaluate(new Float64Array([2, 3, 0])), 19);
    model.setSolution(new Float64Array([2, 3, 0]));
    assert.equal(derived.evaluateSolution(), 38);
    linearSymbol.dispose();
    assert.equal(symbol.evaluateSolution(), 19);
    symbol.dispose();
    assert.throws(() => symbol.id(), { code: "Disposed" });
    assert.equal(derived.evaluate(new Float64Array([2, 3, 0])), 38);
    assert.equal(quadratic.evaluate(new Float64Array([2, 3, 0])), 19);
    model.dispose();
    assert.throws(() => derived.evaluateSolution(), { code: "Disposed" });
    assert.throws(() => quadratic.evaluate(new Float64Array([2, 3, 0])), { code: "Disposed" });
    for (const object of [linear, linearSymbol, reference, xExpression, product, quadratic, twice, derived, cancelled, cancelledLinear, zero, objective, relation, other]) object.dispose();
});
